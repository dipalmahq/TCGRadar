"""Generate one bounded worker service per configured merchant and one notifier."""
import json
from pathlib import Path
import re


def render(shops):
    slugs = [s['slug'] for s in shops]
    if len(slugs) != len(set(slugs)) or any(not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', s) for s in slugs):
        raise ValueError('Merchant slugs must be unique, safe Compose service names')
    lines = ['# Generated by scripts/generate_merchant_workers.py; regenerate after adding merchants.', 'services:']
    roles = [('worker-' + slug, ['python', '-m', 'app.worker', '--merchant', slug]) for slug in slugs]
    roles.append(('notifications', ['python', '-m', 'app.worker', '--notifications-only']))
    for name, command in roles:
        lines.extend(['  ' + name + ':', '    extends:', '      file: compose.yaml', '      service: worker',
                      '    profiles: !reset []', '    command: ' + json.dumps(command), '    environment:',
                      '      RADAR_DATABASE_POOL_SIZE: "2"', '      RADAR_DATABASE_MAX_OVERFLOW: "0"'])
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    shops = json.loads((root / 'config/shops.json').read_text(encoding='utf-8'))
    (root / 'compose.workers.yaml').write_text(render(shops), encoding='utf-8')
    print(f'Generated {len(shops)} merchant workers and one notification worker')
